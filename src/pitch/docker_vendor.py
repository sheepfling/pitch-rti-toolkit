def vendor_docker_payload(*, enable_hla4_preview: bool = False) -> dict[str, str]:
    install_root = vendor_docker_install_root()
    if install_root is None:
        raise ValueError("Could not find a pRTI installation root. Set PITCH_PRTI_HOME or install pRTI first.")

    payload = {
        "PITCH_PRTI_HOME": str(install_root),
        "PITCH_VENDOR_DOCKER_BUILD_ROOT": str(vendor_docker_build_root()),
        "PITCH_VENDOR_DOCKER_SETTINGS_ROOT": str(vendor_docker_settings_root()),
        "PITCH_VENDOR_DOCKER_ENV_FILE": str(vendor_docker_env_path()),
        "PITCH_VENDOR_CONTAINER_WORKDIR": container_path("opt", "prti1516e"),
        "PITCH_VENDOR_CONTAINER_SETTINGS_ROOT": container_path("root", "prti1516e"),
        "LICENSE_SERVER": os.environ.get("LICENSE_SERVER", "pfls"),
        "FEDERATE_COUNT": os.environ.get("FEDERATE_COUNT", "5"),
        "DISABLE_WEB_VIEW": os.environ.get("DISABLE_WEB_VIEW", ""),
        "JAVA_OPTS": os.environ.get("JAVA_OPTS", "-XX:+UseParallelGC -XX:MaxRAMPercentage=75"),
    }
    if enable_hla4_preview:
        payload["CRC_ENABLE_HLA4_PREVIEW"] = "1"
    return payload


def vendor_docker_compose_command(action: str) -> list[str]:
    env_file = vendor_docker_env_path()
    if not env_file.exists():
        raise FileNotFoundError(f"Vendor Docker env file not found: {env_file}. Run `pitch docker init` first.")
    docker_command = resolved_docker_command()
    if docker_command is None:
        raise FileNotFoundError("Could not find the Docker CLI. Install Docker Desktop or Docker Engine first.")
    command = [
        docker_command,
        "compose",
        "--env-file",
        str(env_file),
        "-f",
        str(VENDOR_DOCKER_COMPOSE_PATH),
    ]
    command.extend(action.split())
    return command


def run_vendor_docker_compose(action: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(vendor_docker_compose_command(action), check=False)


def vendor_docker_wait_for_port(host: str, port: int, *, timeout_seconds: float = 60.0, interval_seconds: float = 1.0) -> bool:
    deadline = time.monotonic() + timeout_seconds
    while time.monotonic() < deadline:
        try:
            with socket.create_connection((host, port), timeout=2.0):
                return True
        except OSError:
            time.sleep(interval_seconds)
    return False


def vendor_docker_webview_check(*, timeout_seconds: float = 10.0) -> tuple[bool, str]:
    env_file = vendor_docker_env_path()
    disabled = read_env_value(env_file, "DISABLE_WEB_VIEW")
    if disabled:
        return True, "Vendor Web View probe skipped (DISABLE_WEB_VIEW is set)."
    if not env_file.exists():
        return False, f"Vendor Docker env file not found: {env_file}. Run `pitch docker init` first."
    if not vendor_docker_webview_payload_available():
        return True, "Vendor Web View probe skipped; no Web View payload was staged."

    url = "http://127.0.0.1:8080/webview/"
    request = urllib.request.Request(url, method="GET")
    deadline = time.monotonic() + timeout_seconds
    last_error: str | None = None
    while time.monotonic() < deadline:
        try:
            with urllib.request.urlopen(request, timeout=timeout_seconds) as response:
                response.read(1)
        except urllib.error.HTTPError as exc:
            return True, f"Vendor Web View responded at {url} (HTTP {exc.code})."
        except (urllib.error.URLError, http.client.RemoteDisconnected, TimeoutError, ConnectionResetError) as exc:
            last_error = str(exc)
            time.sleep(0.5)
            continue
        return True, f"Vendor Web View is reachable at {url}."
    if last_error:
        return False, f"Vendor Web View did not respond at {url}: {last_error}"
    return False, f"Vendor Web View did not respond at {url}."


def vendor_docker_smoke_check(*, timeout_seconds: float = 60.0, interval_seconds: float = 1.0) -> tuple[bool, str]:
    if not vendor_docker_wait_for_port("127.0.0.1", 8989, timeout_seconds=timeout_seconds, interval_seconds=interval_seconds):
        return False, "Vendor CRC did not become reachable on 127.0.0.1:8989 within the timeout."

    messages = ["Vendor CRC is reachable on 127.0.0.1:8989."]
    webview_ok, webview_detail = vendor_docker_webview_check(timeout_seconds=10.0)
    messages.append(webview_detail)
    if not webview_ok:
        return False, "\n".join(messages)
    return True, "\n".join(messages)


def vendor_docker_status_lines() -> list[str]:
    lines = [
        "Vendor Docker setup:",
        f"  pRTI home: {vendor_docker_install_root() or 'missing'}",
        f"  env file: {vendor_docker_env_path()}",
        f"  vendor settings overlay: {vendor_docker_settings_root()}",
        f"  vendor build context: {vendor_docker_build_root()}",
        f"  compose file: {VENDOR_DOCKER_COMPOSE_PATH}",
        f"  Web View payload staged: {'yes' if vendor_docker_webview_payload_available() else 'no'}",
    ]
    initialized = vendor_docker_env_path().exists() and vendor_docker_settings_root().exists()
    lines.append(f"  initialized: {'yes' if initialized else 'no'}")
    crc_settings_path = vendor_crc_settings_path(vendor_docker_settings_root())
    if crc_settings_path.exists():
        preview = read_settings_value(crc_settings_path, "CRC.enableHla4PreviewFeatures")
        if preview is not None:
            lines.append(f"  HLA 4 Preview: {preview}")
    return lines
