def container_path(*parts: str) -> str:
    return "/" + "/".join(part.strip("/\\") for part in parts if part)


def vendor_docker_env_path() -> Path:
    override = os.environ.get("PITCH_VENDOR_DOCKER_ENV_FILE", "").strip()
    if override:
        return coerce_env_path(override)
    return VENDOR_DOCKER_ENV_PATH


def vendor_docker_settings_root() -> Path:
    override = os.environ.get("PITCH_VENDOR_DOCKER_SETTINGS_ROOT", "").strip()
    if override:
        return coerce_env_path(override)
    return VENDOR_DOCKER_SETTINGS_ROOT


def vendor_docker_build_root() -> Path:
    override = os.environ.get("PITCH_VENDOR_DOCKER_BUILD_ROOT", "").strip()
    if override:
        return coerce_env_path(override)
    return VENDOR_DOCKER_BUILD_ROOT


def vendor_docker_install_root() -> Path | None:
    override = os.environ.get("PITCH_PRTI_HOME", "").strip()
    if override:
        candidate = coerce_env_path(override)
        return candidate if candidate.exists() else None
    return discovered_prti_install_root()


def write_docker_env_file(path: Path, payload: dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Generated by pitch docker init", "# Safe to edit locally; not tracked by git."]
    for key, value in payload.items():
        lines.append(f"{key}={value}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def copy_vendor_settings(src_root: Path, dest_root: Path) -> None:
    dest_root.mkdir(parents=True, exist_ok=True)
    for filename in ("prti1516eCRC.settings", "prti1516eLRC.settings"):
        source = src_root / "samples" / "docker" / filename
        if source.exists():
            shutil.copy2(source, dest_root / filename)


def copy_vendor_docker_context(src_root: Path, dest_root: Path) -> None:
    dest_root.mkdir(parents=True, exist_ok=True)
    for relative_path in ("lib", "samples/docker", "versioninfo.txt"):
        source = src_root / relative_path
        destination = dest_root / relative_path
        if source.is_dir():
            shutil.copytree(source, destination, dirs_exist_ok=True)
        elif source.is_file():
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, destination)
    _copy_vendor_webview_payload(dest_root)
    _patch_vendor_docker_context(dest_root)


def _vendor_webview_source_roots() -> list[Path]:
    override = os.environ.get(VENDOR_WEBVIEW_INSTALLER_SOURCE_ENV, "").strip()
    installer_drop_root = resolve_installer_drop_root()
    roots: list[Path] = []
    if override:
        roots.append(coerce_env_path(override))
    roots.extend(
        [
            installer_drop_root / VENDOR_WEBVIEW_INSTALLER_DIRNAME,
            installer_drop_root / "webview",
            installer_drop_root,
        ]
    )
    deduped: list[Path] = []
    seen: set[str] = set()
    for root in roots:
        key = str(root)
        if key not in seen:
            deduped.append(root)
            seen.add(key)
    return deduped


def _vendor_webview_payload_candidates(source_root: Path) -> list[Path]:
    if not source_root.exists():
        return []
    if source_root.is_file():
        name = source_root.name.lower()
        if name in {filename.lower() for filename in VENDOR_WEBVIEW_INSTALLER_FILENAMES}:
            return [source_root]
        if name.startswith("pitchwebview_v") and name.endswith("_linux64.sh"):
            return [source_root]
        return []

    candidates: list[Path] = []
    for filename in VENDOR_WEBVIEW_INSTALLER_FILENAMES:
        candidates.extend(path for path in source_root.rglob(filename) if path.is_file())
    for pattern in VENDOR_WEBVIEW_INSTALLER_PATTERNS:
        candidates.extend(path for path in source_root.rglob(pattern) if path.is_file())
    deduped: list[Path] = []
    seen: set[str] = set()
    for candidate in candidates:
        key = str(candidate.resolve()) if candidate.exists() else str(candidate)
        if key not in seen:
            deduped.append(candidate)
            seen.add(key)
    return deduped


def _copy_vendor_webview_payload(dest_root: Path) -> bool:
    payload_root = dest_root / VENDOR_WEBVIEW_INSTALLER_DIRNAME
    payload_root.mkdir(parents=True, exist_ok=True)
    staged = False
    seen_names: set[str] = set()
    for source_root in _vendor_webview_source_roots():
        for candidate in _vendor_webview_payload_candidates(source_root):
            destination = payload_root / candidate.name
            if destination.name in seen_names:
                continue
            shutil.copy2(candidate, destination)
            seen_names.add(destination.name)
            staged = True
    return staged


def vendor_docker_webview_payload_available(*, build_root: Path | None = None) -> bool:
    root = build_root if build_root is not None else vendor_docker_build_root()
    payload_root = root / VENDOR_WEBVIEW_INSTALLER_DIRNAME
    if not payload_root.exists() or not payload_root.is_dir():
        return False
    return any(_vendor_webview_payload_candidates(payload_root))


